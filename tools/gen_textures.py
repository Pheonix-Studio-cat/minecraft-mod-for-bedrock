def crosshair(size=21):
    """Fadenkreuz: vier Striche und ein Punkt, weiss mit dunkler Kontur.

    Die Kontur sorgt dafuer, dass es auf hellem wie dunklem Hintergrund
    sichtbar bleibt.
    """
    mid = size // 2
    white = set()
    for offset in range(2, 7):
        white.add((mid, mid - offset))
        white.add((mid, mid + offset))
        white.add((mid - offset, mid))
        white.add((mid + offset, mid))
    white.add((mid, mid))

    outline = set()
    for x, y in white:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                spot = (x + dx, y + dy)
                if spot not in white and 0 <= spot[0] < size and 0 <= spot[1] < size:
                    outline.add(spot)

    clear = (0, 0, 0, 0)
    bright = (255, 255, 255, 235)
    dark = (0, 0, 0, 170)
    rows = []
    for y in range(size):
        row = []
        for x in range(size):
            if (x, y) in white:
                row.append(bright)
            elif (x, y) in outline:
                row.append(dark)
            else:
                row.append(clear)
        rows.append(row)
    return size, rows


def flat(size, base, accent, border):
    rows = []
    for y in range(size):
        row = []
        for x in range(size):
            edge = x < 2 or y < 2 or x >= size - 2 or y >= size - 2
            if edge:
                row.append(border)
            elif (x // 4 + y // 4) % 2 == 0:
                row.append(base)
            else:
                row.append(accent)
        rows.append(row)
    return rows


