def write_png(path, width, height, rows):
    raw = b""
    for row in rows:
        raw += b"\x00" + b"".join(bytes(px) for px in row)

    def chunk(tag, data):
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    blob = b"\x89PNG\r\n\x1a\n"
    blob += chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
    blob += chunk(b"IDAT", zlib.compress(raw, 9))
    blob += chunk(b"IEND", b"")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(blob)


def from_art(path, art):
    lines = [line for line in art.strip("\n").split("\n")]
    size = max(len(lines), max(len(line) for line in lines))
    rows = []
    for y in range(size):
        line = lines[y] if y < len(lines) else ""
        line = line.ljust(size, ".")
        rows.append([PALETTE[ch] for ch in line[:size]])
    write_png(path, size, size, rows)


